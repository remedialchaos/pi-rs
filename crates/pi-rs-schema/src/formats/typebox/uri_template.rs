use regress::Regex;
use std::sync::LazyLock;

/// Whether the value is a URI template (RFC 6570).
static URI_TEMPLATE: LazyLock<Regex> = LazyLock::new(|| {
    Regex::with_flags(r##"^(?:(?:[^\x00-\x20"<>%\\^`{|}\x7f]|%[0-9a-f]{2})|\{[+#./;?&=,!@|]?(?:[a-z0-9_]|%[0-9a-f]{2})+(?:\.(?:[a-z0-9_]|%[0-9a-f]{2})+)*(?::[1-9]\d{0,3}|\*)?(?:,(?:[a-z0-9_]|%[0-9a-f]{2})+(?:\.(?:[a-z0-9_]|%[0-9a-f]{2})+)*(?::[1-9]\d{0,3}|\*)?)*\})*$"##, "i").expect("the pattern is valid")
});

/// Whether the value has the format.
pub fn is_uri_template(value: &str) -> bool {
    URI_TEMPLATE.find(value).is_some()
}
